import type { AnimeItem, AnimeEpisode } from '../utils/animeLogic';

function buildEpisodes(
  animeId: string,
  count: number,
  dubCount: number,
  customFirstEpisodes?: Array<{ title: string; description: string; aired: string }>
): AnimeEpisode[] {
  const list: AnimeEpisode[] = [];
  const limit = Math.min(count, 24);
  for (let i = 1; i <= limit; i++) {
    const custom = customFirstEpisodes?.[i - 1];
    list.push({
      number: i,
      id: `${animeId}-ep-${i}`,
      title: custom?.title ?? `Episode ${i}: Awakening of Fate`,
      description:
        custom?.description ??
        `Episode ${i} escalates the confrontation as hidden powers surface and alliances are tested in the heat of battle.`,
      duration: '23:55',
      durationMinutes: 24,
      aired: custom?.aired ?? `Oct ${Math.min(28, i * 2)}, 2025`,
      hasSub: true,
      hasDub: i <= dubCount,
      hasDubtitles: i <= dubCount,
    });
  }
  return list;
}

